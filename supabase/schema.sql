create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  title text not null,
  year integer not null check (year between 1888 and 2100),
  genre text not null,
  language text not null,
  rating numeric(3,1) not null default 0 check (rating between 0 and 10),
  director text not null default '',
  cast_members text not null default '',
  description text not null default '',
  poster text not null,
  backdrop text not null,
  trailer_url text,
  telegram_url text,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.movies enable row level security;

grant select on public.movies to anon, authenticated;
grant all on public.movies to service_role;

-- Visitors can only read published catalog entries. Writes are performed by the protected Vercel API.
drop policy if exists "Public can read published movies" on public.movies;
create policy "Public can read published movies"
  on public.movies for select to anon, authenticated
  using (is_published = true);

create index if not exists movies_published_created_at_idx
  on public.movies (is_published, created_at desc);
create index if not exists movies_title_idx on public.movies (title);

-- Do not create public insert/update/delete policies. The server API uses the secret key only on Vercel.
